"""Generate frontend/src/app/feature-schema.ts from the real data.
Run from the project root AFTER the Angular app exists:  python backend/make_schema.py
"""
import json
import math
from pathlib import Path

import joblib
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
features = joblib.load(ROOT / "backend/models/model_bundle.joblib")["features"]
df = pd.read_csv(ROOT / "data/health_lifestyle_classification.csv",
                 keep_default_na=False, na_values=[""])

fields = []
for name in features:
    col = df[name]
    label = name.replace("_", " ").title()
    if pd.api.types.is_numeric_dtype(col):
        fields.append({"name": name, "label": label, "kind": "number", "required": True,
                       "min": math.floor(col.min()), "max": math.ceil(col.max())})
    else:
        fields.append({"name": name, "label": label, "kind": "category", "required": True,
                       "options": sorted(col.dropna().astype(str).unique().tolist())})

ts = """export type Feature = {
  name: string;
  label: string;
  kind: 'number' | 'category';
  required: boolean;
  options?: string[];
  min?: number;
  max?: number;
};

// AUTO-GENERATED by backend/make_schema.py - do not edit by hand.
export const FEATURES: Feature[] = """ + json.dumps(fields, indent=2) + ";\n"
out = ROOT / "frontend/src/app/feature-schema.ts"
out.write_text(ts, encoding="utf-8")
print(f"Wrote {out} with {len(fields)} fields")